"""Validated JSON answer contract and short, source-grounded chat rendering."""
import re

DETAIL = re.compile(r'\b(explain in detail|detailed|step.by.step|full explanation|elaborate|in depth|complete list|list all|show all)\b', re.I)
JSON_REQUEST = re.compile(r'\b(?:as json|in json|json format|show json|return json)\b', re.I)
SENTENCES = re.compile(r'(?<=[.!?])\s+(?=[A-Z0-9])')


def expanded_requested(question):
    return bool(DETAIL.search(question or ''))


def concise(text, question='', max_words=60, max_sentences=2):
    value = re.sub(r'<think>.*?</think>', '', str(text or ''), flags=re.I | re.S)
    value = re.sub(r'<think>.*$', '', value, flags=re.I | re.S).strip()
    if expanded_requested(question):
        return value
    lines = [line.strip() for line in value.splitlines() if line.strip()]
    if len(lines) > 6:
        value = '\n'.join(lines[:6]) + f'\n… {len(lines)-6} more items.'
    else:
        value = '\n'.join(lines)
    if '\n' not in value:
        value = ' '.join(SENTENCES.split(value)[:max(1, max_sentences)])
    words = value.split()
    if len(words) > max(12, max_words):
        value = ' '.join(words[:max(12, max_words)]).rstrip(',;:') + '…'
    return value


def format_chat(reply, question, settings, intent='company'):
    """Build the JSON object before returning it to the desktop client."""
    if not isinstance(reply, dict):
        raise TypeError('Chat response must be an object')
    if reply.get('type') not in ('answer', 'db_connect_required', 'db_table_selection_required',
                                  'report_table_selection_required', 'report_ready'):
        return reply
    policy = settings.get('response', {})
    key = 'message' if reply['type'] in ('db_connect_required', 'db_table_selection_required', 'report_table_selection_required') else 'answer'
    # Evidence inventories are already bounded by the retrieval layer.
    # Do not collapse them to six lines or two sentences.
    display_question = (question + ' complete list') if reply.get('detailed_evidence') else question
    message = concise(reply.get(key, ''), display_question,
                      max(12, min(250, int(policy.get('default_max_words', 60)))),
                      max(1, min(8, int(policy.get('default_max_sentences', 2)))))
    sources = list(dict.fromkeys(str(s) for s in reply.get('sources', []) if s))[:10]
    structured = {
        'schema_version': '1.0',
        'intent': intent,
        'status': 'ok' if reply['type'] == 'answer' else reply['type'],
        'answer': message,
        'sources': sources,
        'grounding': ('document' if sources else 'model' if intent == 'general' else
                      'database' if intent in ('database', 'report') else 'none'),
        'expanded': expanded_requested(question),
        'learning': 'approved_sources_only',
        'tool': reply.get('tool'),
    }
    for field in ('database_count', 'table_count', 'row_count', 'path', 'sql'):
        if field in reply:
            structured[field] = reply[field]
    # Inventory metadata is verified by the local filesystem, not generated by Qwen3.
    if reply.get('tool') == 'recent_documents':
        for field in ('date', 'activity', 'files', 'last_sync', 'timestamp_fallback_used'):
            if field in reply:
                structured[field] = reply[field]
    if 'query_result' in reply:
        structured['query_result'] = reply['query_result']
    if 'document_count' in reply:
        structured['document_count'] = int(reply['document_count'])
        structured['inventory_last_sync'] = str(reply.get('inventory_last_sync', ''))
        structured['grounding'] = 'file_inventory'
    reply = dict(reply)
    reply[key] = message
    reply['response_json'] = structured
    reply['presentation'] = 'json' if JSON_REQUEST.search(question) else 'text'
    return reply
